import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 }, colorScheme: 'light' });
const p = await ctx.newPage();
p.on('dialog', (d) => d.accept());
p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await p.goto('http://localhost:4610/#k8t7onxc'); await p.waitForTimeout(3500);
await p.click('#tplBtn'); await p.waitForTimeout(500);
await p.click('.tpl-card[data-id="weihnachten"]'); await p.waitForTimeout(9000);
await p.screenshot({ path: '/tmp/ui/9-templates.png' });
await p.click('text=Apply and lay out pages again'); await p.waitForTimeout(500);
await p.waitForTimeout(4000);
await p.screenshot({ path: '/tmp/ui/10-light.png' });
await p.click('#views button:nth-child(2)'); await p.waitForTimeout(3000);
await p.screenshot({ path: '/tmp/ui/11-cover.png' });
await p.click('#aiBtn'); await p.waitForTimeout(1200);
await p.screenshot({ path: '/tmp/ui/12-connect.png' });
