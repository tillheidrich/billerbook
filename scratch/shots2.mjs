import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await p.goto('http://localhost:4610/#k8t7onxc'); await p.waitForTimeout(3500);
await p.keyboard.press('ArrowRight'); await p.waitForTimeout(2000);
const t = await p.$$('.text-edit'); await t[t.length - 1].click(); await p.waitForTimeout(800);
await p.screenshot({ path: '/tmp/ui/2-text.png' });
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
const fr = await p.$$('.frame.has'); await fr[0].click(); await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/ui/3-frame.png' });
await p.keyboard.press('Shift+P'); await p.waitForTimeout(3500);
await p.screenshot({ path: '/tmp/ui/4-proof.png' });
await p.keyboard.press('p'); await p.waitForTimeout(300);
await p.click('text=Cover'); await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/ui/6-cover.png' });
await p.click('text=Pages'); await p.waitForTimeout(1500);
const t2 = await p.$$('.text-edit'); await t2[0].click(); await p.waitForTimeout(500);
await p.click('text=Fonts & styles…'); await p.waitForTimeout(1500);
await p.screenshot({ path: '/tmp/ui/7-styles.png' });
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
await p.click('#exportBtn'); await p.waitForTimeout(800);
await p.screenshot({ path: '/tmp/ui/5-export.png' });
b.close();
